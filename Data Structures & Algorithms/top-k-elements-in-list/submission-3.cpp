/*
initial solve
--------------
use bucket sort but with modification
bucket sort in general have several condition
- the key can be calculated or generated by the context of the problem
- the buckets or index are in order
- each bucket can store more than one elements

the solve:
- use count as a key and store the elements inside the key according to how much they appear (count)
- one bucket or key can have multiple elements
- the index size is the same as the n size (because maximum distinct count of n size is n)
- use hashmap to count all the elments
- iterate through the hashmap and store it into the bucket array
- once all of them are stored, start iterating from the last index (highest count), until all the K required elements are printed
*/

class Solution {
public:
    vector<int> topKFrequent(vector<int>& nums, int k) {
        int size = nums.size();
        unordered_map<int, int> elementCount;

        // count the occurences of each element
        for(int i = 0; i < size; i++){
            elementCount[nums[i]]++;
        }

        // store it inside bucket
        vector<vector<int>> bucket(size + 1);
        for(const auto& [key, value] : elementCount){
            bucket[value].push_back(key);
        }

        // iterate from last index (most occurence)
        vector<int> result;
        for(int i = size; i >= 0; i--){
            for(int num : bucket[i]){
                result.push_back(num);
                if(result.size() >= k){
                    return result;
                }
            }
        }

        return result;
    }
};
